// Differential self-test for the *JavaScript* target model.
//
// Two things happen here:
//   1. We emit a Dart program (`_generated_probe`) that performs every sampled
//      operation in ordinary Dart code and prints the result of each.
//   2. We compile that program with the real `dart compile js` and run it under
//      Node, then compare each printed value with what TargetEvaluator(js)
//      predicts.
//
// Run with: dart run tool/verify_js_model.dart
// Requires: dart (with dart2js) and node on PATH.

import 'dart:io';

import 'package:path/path.dart' as p;

import 'package:web_int_checker/src/model.dart';
import 'package:web_int_checker/src/target_semantics.dart';

const operands = <int>[
  0, 1, -1, 2, 3, -3, 7, -7, 31, 32, 33, 63, 64, 65,
  1 << 20, 1 << 30, 1 << 31, 1 << 32, 1 << 40, 1 << 52, 1 << 53,
  -(1 << 31), -(1 << 32), -(1 << 40), -(1 << 52), -(1 << 53),
  0x7FFFFFFF, -0x80000000, 0xFFFFFFFF, 0x100000000,
  0x7FFFFFFFFFFFFFFF, -0x8000000000000000,
  9007199254740991, 9007199254740992, -9007199254740992,
  123456789012345, -123456789012345, 4294967295, 4294967296,
];

const shifts = <int>[0, 1, 5, 30, 31, 32, 33, 40, 62, 63, 64, 65, 100];

/// A single sampled operation, identified by a stable label.
class Op {
  const Op(this.label, this.a, this.b, this.kind);
  final String label;
  final int a;
  final int b;
  final String kind; // add sub mul and or xor tdiv mod shl shr ushr
}

List<Op> generateOps() {
  final ops = <Op>[];
  for (final a in operands) {
    for (final b in operands) {
      // ignore: unnecessary_brace_in_string_interps
      final l = '${a}_${b}';
      ops.add(Op('add_$l', a, b, 'add'));
      ops.add(Op('sub_$l', a, b, 'sub'));
      ops.add(Op('mul_$l', a, b, 'mul'));
      ops.add(Op('and_$l', a, b, 'and'));
      ops.add(Op('or_$l', a, b, 'or'));
      ops.add(Op('xor_$l', a, b, 'xor'));
      if (b != 0) {
        ops.add(Op('tdiv_$l', a, b, 'tdiv'));
        ops.add(Op('mod_$l', a, b, 'mod'));
      }
    }
    for (final s in shifts) {
      ops.add(Op('shl_${a}_$s', a, s, 'shl'));
      ops.add(Op('shr_${a}_$s', a, s, 'shr'));
      ops.add(Op('ushr_${a}_$s', a, s, 'ushr'));
    }
  }
  return ops;
}

/// The expression as it must appear in the generated probe program.
String _expr(Op op) {
  final a = 'A[${operands.indexOf(op.a)}]';
  if (op.kind == 'shl' || op.kind == 'shr' || op.kind == 'ushr') {
    return '$a ${_opToken(op.kind)} ${op.b}';
  }
  final b = 'A[${operands.indexOf(op.b)}]';
  return '$a ${_opToken(op.kind)} $b';
}

String _opToken(String kind) => switch (kind) {
  'add' => '+',
  'sub' => '-',
  'mul' => '*',
  'and' => '&',
  'or' => '|',
  'xor' => '^',
  'tdiv' => '~/',
  'mod' => '%',
  'shl' => '<<',
  'shr' => '>>',
  'ushr' => '>>>',
  _ => throw StateError(kind),
};

String generateProbe(List<Op> ops) {
  final buf = StringBuffer();
  buf.writeln('// GENERATED by tool/verify_js_model.dart - do not edit.');
  buf.writeln('void main() {');
  if (_operandsCompileForJs) {
    buf.writeln('  const A = <int>[${operands.join(', ')}];');
  } else {
    // Some operands are not representable as JS integer literals; build them
    // with int.parse so the probe itself compiles. This does not weaken the
    // comparison: each operand still has exactly the value the model uses.
    buf.writeln('  final A = <int>[${operands.map(_jsSafeLiteral).join(', ')}];');
  }
  buf.writeln('  void t(String k, Object v) => print("\$k=\$v");');
  for (final op in ops) {
    buf.writeln('  t("${op.label}", ${_expr(op)});');
  }
  buf.writeln('}');
  return buf.toString();
}

/// Whether every sampled operand is directly writable as a JS int literal.
final bool _operandsCompileForJs =
    operands.every((v) => isExactlyRepresentableAsDouble(BigInt.from(v)));

String _jsSafeLiteral(int v) =>
    isExactlyRepresentableAsDouble(BigInt.from(v))
        ? '$v'
        : "int.parse('$v')";

/// What the model predicts for [op] on the JS target, as a numeric value.
///
/// Returns a [double] (JS `int` is a double) or the string 'THROW'. Values are
/// compared numerically rather than by their printed form, because JS and the
/// Dart VM format doubles differently (`9223372036854776000` vs
/// `9223372036854776000.0`); that difference is cosmetic, not semantic.
Object predictJs(Op op, TargetEvaluator ev) {
  final a = BigInt.from(op.a);
  final b = BigInt.from(op.b);
  try {
    final value = switch (op.kind) {
      'add' => ev.add(a, b),
      'sub' => ev.subtract(a, b),
      'mul' => ev.multiply(a, b),
      'and' => ev.bitAnd(a, b),
      'or' => ev.bitOr(a, b),
      'xor' => ev.bitXor(a, b),
      'tdiv' => ev.truncatingDivide(a, b),
      'mod' => ev.modulo(a, b),
      'shl' => ev.shiftLeft(a, b),
      'shr' => ev.shiftRight(a, b),
      'ushr' => ev.unsignedShiftRight(a, b),
      _ => throw StateError(op.kind),
    };
    return value is BigInt ? value.toDouble() : value as double;
  } on UndefinedIntegerOperation {
    return 'THROW';
  }
}

/// Compare a model prediction with the string printed by the JS program.
bool agrees(Object model, String? printed) {
  if (model == 'THROW') return printed == 'THROW' || printed == 'NaN';
  if (printed == null) return false;
  if (printed == 'THROW') return false;
  final actual = double.tryParse(printed);
  if (actual == null) return false;
  final want = model as double;
  if (want.isNaN) return actual.isNaN;
  if (!want.isFinite) return actual == want;
  // Normalise -0.0 and 0.0: they print differently but are numerically equal
  // and carry no security-relevant distinction here.
  return actual == want;
}

Future<void> main() async {
  final ops = generateOps();
  final dir = Directory.systemTemp.createTempSync('wic_jscheck_');
  final dartFile = File(p.join(dir.path, 'probe.dart'));
  final jsFile = p.join(dir.path, 'probe.js');
  dartFile.writeAsStringSync(generateProbe(ops));

  stdout.writeln('Compiling ${ops.length} sampled operations with dart2js...');
  final compile = await Process.run(
    Platform.resolvedExecutable,
    ['compile', 'js', '-O0', '-o', jsFile, dartFile.path],
  );
  if (compile.exitCode != 0) {
    stderr.writeln(compile.stdout);
    stderr.writeln(compile.stderr);
    exit(1);
  }

  final run = await Process.run('node', [jsFile]);
  if (run.exitCode != 0) {
    stderr.writeln(run.stdout);
    stderr.writeln(run.stderr);
    exit(1);
  }

  final actual = <String, String>{};
  for (final line in (run.stdout as String).split('\n')) {
    final i = line.indexOf('=');
    if (i <= 0) continue;
    actual[line.substring(0, i)] = line.substring(i + 1).trim();
  }

  const ev = TargetEvaluator(Target.js);
  var failures = 0;
  for (final op in ops) {
    final want = predictJs(op, ev);
    final got = actual[op.label];
    if (!agrees(want, got)) {
      failures++;
      if (failures <= 40) {
        stdout.writeln('MISMATCH ${op.label} model=$want js=$got');
      }
    }
  }

  stdout.writeln(failures == 0
      ? 'OK: JS model matches dart2js for all ${ops.length} sampled operations'
      : 'FAILED: $failures / ${ops.length} mismatches');
  dir.deleteSync(recursive: true);
  if (failures != 0) exit(1);
}
